/* Commit the generated HTML/assets so GitHub Pages can serve static production files. */
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const Babel = require('@babel/standalone');
const root = path.resolve(__dirname, '..');
const assets = path.join(root, 'assets');
fs.mkdirSync(assets, { recursive: true });
const fingerprint = body => createHash('sha256').update(body).digest('hex').slice(0, 12);
const source = ['src/home-covers.jsx', 'src/app.jsx'].map(file => fs.readFileSync(path.join(root, file), 'utf8')).join('\n');
const js = Babel.transform(source, { presets: [['react', { runtime: 'classic' }]], comments: false, compact: true, minified: true }).code;
const appFile = `app.${fingerprint(js)}.js`;
fs.writeFileSync(path.join(assets, appFile), js + '\n');
const cli = path.join(path.dirname(require.resolve('tailwindcss/package.json')), 'lib/cli.js');
const temporaryCss = path.join(assets, 'styles.build.css');
execFileSync(process.execPath, [cli, '-c', 'tailwind.config.cjs', '-i', 'src/tailwind.css', '-o', temporaryCss, '--minify'], { cwd: root, stdio: 'inherit' });
const css = fs.readFileSync(temporaryCss);
const cssFile = `styles.${fingerprint(css)}.css`;
fs.writeFileSync(path.join(assets, cssFile), css);
fs.unlinkSync(temporaryCss);
for (const [name, relative, target] of [
    ['react', 'umd/react.production.min.js', 'react.18.3.1.min.js'],
    ['react-dom', 'umd/react-dom.production.min.js', 'react-dom.18.3.1.min.js'],
    ['hls.js', 'dist/hls.min.js', 'hls.1.6.16.min.js']
]) fs.copyFileSync(path.join(path.dirname(require.resolve(name + '/package.json')), relative), path.join(assets, target));
const template = fs.readFileSync(path.join(root, 'src/index.template.html'), 'utf8');
fs.writeFileSync(path.join(root, 'index.html'), '<!-- Generated by npm run build; edit src/ files. -->\n' + template.replace('{{APP_JS}}', appFile).replace('{{CSS}}', cssFile));
console.log('Production HTML, compiled JSX, Tailwind CSS and pinned browser libraries generated.');
